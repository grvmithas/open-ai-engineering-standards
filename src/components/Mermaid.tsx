'use client';

import { useEffect, useId, useState } from 'react';

interface MermaidProps {
  chart: string;
}

let mermaidReady: Promise<typeof import('mermaid').default> | null = null;

function getMermaid() {
  if (!mermaidReady) {
    mermaidReady = import('mermaid').then(({ default: mermaid }) => {
      mermaid.initialize({
        startOnLoad: false,
        theme: 'neutral',
        securityLevel: 'strict',
        fontFamily: 'ui-sans-serif, system-ui, sans-serif',
        flowchart: {
          htmlLabels: true,
          curve: 'basis',
          padding: 14,
          nodeSpacing: 36,
          rankSpacing: 44,
          diagramPadding: 8,
          useMaxWidth: true,
        },
        sequence: {
          useMaxWidth: true,
          mirrorActors: false,
        },
        themeVariables: {
          background: '#ffffff',
          primaryColor: '#dbeafe',
          primaryTextColor: '#0f172a',
          primaryBorderColor: '#1d4ed8',
          secondaryColor: '#dcfce7',
          secondaryTextColor: '#14532d',
          secondaryBorderColor: '#15803d',
          tertiaryColor: '#fef3c7',
          tertiaryTextColor: '#78350f',
          tertiaryBorderColor: '#d97706',
          lineColor: '#1e293b',
          textColor: '#0f172a',
          mainBkg: '#ffffff',
          nodeBorder: '#1e293b',
          clusterBkg: '#f1f5f9',
          clusterBorder: '#334155',
          titleColor: '#0f172a',
          edgeLabelBackground: '#ffffff',
          actorBkg: '#dbeafe',
          actorBorder: '#1d4ed8',
          actorTextColor: '#0f172a',
          actorLineColor: '#334155',
          signalColor: '#0f172a',
          signalTextColor: '#0f172a',
          labelBoxBkgColor: '#ffffff',
          labelTextColor: '#0f172a',
          noteBkgColor: '#fef9c3',
          noteTextColor: '#422006',
          noteBorderColor: '#ca8a04',
          fontSize: '16px',
        },
      });
      return mermaid;
    });
  }
  return mermaidReady;
}

/** Ensure SVG does not inherit the dark-theme prose text color via currentColor. */
function hardenSvgContrast(svg: string): string {
  return svg
    .replaceAll('currentColor', '#0f172a')
    .replace(
      /<svg\b([^>]*)>/,
      '<svg$1 style="color:#0f172a;background:#ffffff;max-width:100%;height:auto;">',
    );
}

export default function Mermaid({ chart }: MermaidProps) {
  const reactId = useId();
  const [svg, setSvg] = useState('');
  const [error, setError] = useState('');

  useEffect(() => {
    let alive = true;

    getMermaid()
      .then(async mermaid => {
        const id = `mmd-${reactId.replace(/[^a-zA-Z0-9]/g, '')}`;
        const { svg: rendered } = await mermaid.render(id, chart);
        if (!alive) return;
        setSvg(hardenSvgContrast(rendered));
        setError('');
      })
      .catch((err: unknown) => {
        console.error('Mermaid render error:', err);
        if (!alive) return;
        setError(err instanceof Error ? err.message : 'Failed to render diagram.');
      });

    return () => {
      alive = false;
    };
  }, [chart, reactId]);

  if (error) {
    return (
      <div className="my-4 rounded-lg border border-red-800/50 bg-red-950/30 p-4 font-mono text-xs text-red-300">
        <strong>Mermaid render error</strong>
        <p className="mt-1">{error}</p>
      </div>
    );
  }

  if (!svg) {
    return (
      <div className="mermaid-panel mermaid-panel--loading my-6 flex h-40 items-center justify-center">
        <div className="spinner" />
      </div>
    );
  }

  return (
    <figure className="mermaid-panel my-6 not-prose">
      <div
        className="mermaid-canvas"
        // SVG is generated by Mermaid from trusted local markdown.
        dangerouslySetInnerHTML={{ __html: svg }}
      />
    </figure>
  );
}
